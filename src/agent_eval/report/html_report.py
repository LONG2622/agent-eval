"""HTML report generator for agent evaluation results.

Provides three report types:
  1. **Single-run detail** – full trace timeline + per-step evaluation scores
  2. **Batch summary**    – KPI cards, radar chart, latency histogram, token pie
  3. **A/B comparison**   – side-by-side radar, delta table, significance notes

Charts are rendered via Chart.js (CDN) so the HTML file is self-contained and
can be opened directly in a browser without a local server.
"""

from __future__ import annotations

import json
import time
from datetime import datetime
from pathlib import Path
from typing import Any

from agent_eval.evaluation.ab_test import ABTestSummary
from agent_eval.evaluation.engine import BatchSummary, EvaluationEngine
from agent_eval.trace import JSONLStorage, RunRecord, Span

