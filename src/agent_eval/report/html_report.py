class HTMLReportGenerator:
    """Generate HTML reports for agent evaluation results."""

    def __init__(self, output_dir: str | Path | None = None) -> None:
        from agent_eval.config import load_config

        cfg = load_config()
        out = Path(output_dir or cfg.storage.output_dir) / "reports"
        out.mkdir(parents=True, exist_ok=True)
        self._output_dir = out

    # ------------------------------------------------------------------
    # 1. Single-run detail report
    # ------------------------------------------------------------------
    def generate_single_run_report(
        self,
        run_id: str,
        storage: JSONLStorage | None = None,
    ) -> Path:
        """Generate a detailed HTML report for a single run."""
        storage = storage or JSONLStorage()
        run = storage.load_run(run_id)
        if run is None:
            raise KeyError(f"Run {run_id} not found")
        spans = storage.load_spans(run_id)
        engine = EvaluationEngine(storage=storage)
        eval_results = engine.get_run_results(run_id) or engine.evaluate_run(run_id)

        body = self._build_single_run_body(run, spans, eval_results)
        return self._write_report(
            f"run_{run_id}",
            title=f"Run Report: {run_id[:12]}",
            subtitle=f"Task: {run.input_text[:60]} · Agent: {run.agent_name}",
            body=body,
        )

    # ------------------------------------------------------------------
    # 2. Batch summary report
    # ------------------------------------------------------------------
    def generate_batch_report(
        self,
        summary: BatchSummary,
        *,
        label: str = "batch",
    ) -> Path:
        """Generate a summary HTML report for a batch evaluation."""
        body = self._build_batch_body(summary)
        return self._write_report(
            f"batch_{label}_{int(time.time())}",
            title="Batch Evaluation Report",
            subtitle=f"Tasks: {summary.total_runs} · Evaluators: {', '.join(summary.metadata.get('evaluators', []))}",
            body=body,
        )

    # ------------------------------------------------------------------
    # 3. A/B comparison report
    # ------------------------------------------------------------------
    def generate_ab_report(
        self,
        summary: ABTestSummary,
    ) -> Path:
        """Generate an A/B comparison HTML report."""
        body = self._build_ab_body(summary)
        return self._write_report(
            f"ab_{summary.agent_a_name}_vs_{summary.agent_b_name}_{int(time.time())}",
            title="A/B Comparison Report",
            subtitle=f"{summary.agent_a_name} vs {summary.agent_b_name} · {summary.total_tasks} tasks",
            body=body,
        )

    # ------------------------------------------------------------------
    # Internal builders
    # ------------------------------------------------------------------
    def _build_single_run_body(
        self,
        run: RunRecord,
        spans: list[Span],
        eval_results: list[Any],
    ) -> str:
        # KPI cards
        status_class = "green" if run.status.value == "success" else "orange"
        kpi_html = f"""
        <div class="kpi-grid">
          <div class="kpi-card">
            <div class="kpi-label">Status</div>
            <div class="kpi-value {status_class}">{run.status.value}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Latency</div>
            <div class="kpi-value blue">{run.total_latency_ms} ms</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Total Tokens</div>
            <div class="kpi-value purple">{run.tokens.total_tokens}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Cost</div>
            <div class="kpi-value orange">${run.total_cost:.4f}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Steps</div>
            <div class="kpi-value green">{run.total_steps}</div>
          </div>
        </div>"""

        # Trace timeline
        trace_html = '<div class="section"><h2>Execution Trace</h2>'
        for span in spans:
            span_type_label = span.span_type.value
            color_map = {"llm_call": "#3b82f6", "tool_call": "#10b981",
                         "agent_step": "#f59e0b", "thought": "#8b5cf6"}
            color = color_map.get(span_type_label, "#6b7280")
            input_preview = json.dumps(span.input_data, ensure_ascii=False)[:200]
            output_preview = json.dumps(span.output_data, ensure_ascii=False)[:200]
            trace_html += f"""
            <div class="trace-step" style="border-color: {color}">
              <div class="step-header">Step {span.step_index} · {span_type_label} · {span.name} · {span.latency_ms}ms</div>
              <div class="step-detail"><b>Input:</b> {input_preview}</div>
              <div class="step-detail"><b>Output:</b> {output_preview}</div>
            </div>"""
        trace_html += "</div>"

        # Evaluation results
        eval_html = '<div class="section"><h2>Evaluation Results</h2><table><tr>'
        eval_html += "<th>Evaluator</th><th>Dimension</th><th>Sub-metric</th><th>Score</th><th>Passed</th><th>Details</th></tr>"
        for r in eval_results:
            passed_badge = '<span class="badge badge-success">PASS</span>' if r.passed else '<span class="badge badge-fail">FAIL</span>'
            detail_str = json.dumps(r.details, ensure_ascii=False)[:100] if r.details else ""
            eval_html += f"""<tr>
                <td>{r.evaluator}</td>
                <td>{r.dimension.value}</td>
                <td>{r.sub_metric.value if r.sub_metric else "—"}</td>
                <td>{r.score:.4f}</td>
                <td>{passed_badge}</td>
                <td>{detail_str}</td>
              </tr>"""
        eval_html += "</table></div>"

        # Final answer
        answer_html = f"""
        <div class="section">
          <h2>Final Answer</h2>
          <div style="background: #f8fafc; padding: 16px; border-radius: 8px; white-space: pre-wrap;">
            {run.final_output or "(no output)"}
          </div>
        </div>"""

        return kpi_html + trace_html + eval_html + answer_html

    def _build_batch_body(self, summary: BatchSummary) -> str:
        # KPI cards
        kpi_html = f"""
        <div class="kpi-grid">
          <div class="kpi-card">
            <div class="kpi-label">Total Runs</div>
            <div class="kpi-value blue">{summary.total_runs}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Success Rate</div>
            <div class="kpi-value green">{summary.overall_success_rate:.1%}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Avg Quality</div>
            <div class="kpi-value purple">{summary.overall_quality_score:.2f}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Avg Latency</div>
            <div class="kpi-value orange">{summary.avg_latency_ms:.0f} ms</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Total Tokens</div>
            <div class="kpi-value blue">{summary.total_tokens:,}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Total Cost</div>
            <div class="kpi-value orange">${summary.total_cost:.4f}</div>
          </div>
        </div>"""

        # Dimension radar chart
        dim_labels = list(summary.dimension_summaries.keys())
        dim_means = [round(summary.dimension_summaries[d].mean_score, 3) for d in dim_labels]
        radar_chart_id = "radarChart"
        radar_script = f"""
        (function() {{
          const ctx = document.getElementById('{radar_chart_id}');
          if (!ctx) return;
          new Chart(ctx, {{
            type: 'radar',
            data: {{
              labels: {json.dumps(dim_labels)},
              datasets: [{{
                label: 'Mean Score',
                data: {json.dumps(dim_means)},
                backgroundColor: 'rgba(59, 130, 246, 0.2)',
                borderColor: 'rgba(59, 130, 246, 1)',
                borderWidth: 2,
              }}]
            }},
            options: {{
              responsive: true,
              maintainAspectRatio: false,
              scales: {{ r: {{ beginAtZero: true, max: 1.0 }} }}
            }}
          }});
        }})();
        """

        # Dimension table
        dim_table = '<div class="section"><h2>Dimension Breakdown</h2><table><tr>'
        dim_table += "<th>Dimension</th><th>Count</th><th>Mean</th><th>Median</th><th>Pass Rate</th><th>Min</th><th>Max</th></tr>"
        for dim, ds in summary.dimension_summaries.items():
            dim_table += f"""<tr>
                <td>{dim}</td><td>{ds.count}</td><td>{ds.mean_score:.4f}</td>
                <td>{ds.median_score:.4f}</td><td>{ds.pass_rate:.1%}</td>
                <td>{ds.min_score:.4f}</td><td>{ds.max_score:.4f}</td>
              </tr>"""
        dim_table += "</table></div>"

        # Top failures
        fail_html = '<div class="section"><h2>Top Failures</h2>'
        if summary.top_failures:
            fail_html += '<table><tr><th>Run ID</th><th>Task</th><th>Score</th></tr>'
            for f in summary.top_failures:
                fail_html += f'<tr><td>{f["run_id"][:12]}</td><td>{f["preview"]}</td><td>{f["score"]:.4f}</td></tr>'
            fail_html += "</table>"
        else:
            fail_html += "<p>No failures.</p>"
        fail_html += "</div>"

        chart_html = f'<div class="section"><h2>Dimension Radar</h2><div class="chart-container"><canvas id="{radar_chart_id}"></canvas></div></div>'

        return kpi_html + chart_html + dim_table + fail_html, radar_script

    def _build_ab_body(self, summary: ABTestSummary) -> str:
        overall = summary.overall
        if not overall:
            return "<div class='section'><p>No comparison data available.</p></div>", ""

        # KPI comparison
        a = overall.get("agent_a", {})
        b = overall.get("agent_b", {})
        delta = overall.get("delta", {})

        def _delta_cell(val: float, is_ratio: bool = False) -> str:
            cls = "diff-positive" if val > 0 else "diff-negative" if val < 0 else ""
            sign = "+" if val > 0 else ""
            if is_ratio:
                return f'<span class="{cls}">{sign}{val:.2f}x</span>'
            return f'<span class="{cls}">{sign}{val:.4f}</span>'

        kpi_html = f"""
        <div class="kpi-grid">
          <div class="kpi-card">
            <div class="kpi-label">Metric</div>
            <div class="kpi-value" style="font-size:14px">Agent A</div>
            <div class="kpi-value" style="font-size:14px">Agent B</div>
            <div class="kpi-value" style="font-size:14px">Delta</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Success Rate</div>
            <div class="kpi-value green">{a.get("success_rate", 0):.1%}</div>
            <div class="kpi-value green">{b.get("success_rate", 0):.1%}</div>
            <div class="kpi-value">{_delta_cell(delta.get("success_rate", 0))}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Quality</div>
            <div class="kpi-value purple">{a.get("quality_score", 0):.2f}</div>
            <div class="kpi-value purple">{b.get("quality_score", 0):.2f}</div>
            <div class="kpi-value">{_delta_cell(delta.get("quality_score", 0))}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Avg Latency</div>
            <div class="kpi-value blue">{a.get("avg_latency_ms", 0):.0f}ms</div>
            <div class="kpi-value blue">{b.get("avg_latency_ms", 0):.0f}ms</div>
            <div class="kpi-value">{_delta_cell(delta.get("avg_latency_ratio", 0), is_ratio=True)}</div>
          </div>
          <div class="kpi-card">
            <div class="kpi-label">Total Tokens</div>
            <div class="kpi-value orange">{a.get("total_tokens", 0):,}</div>
            <div class="kpi-value orange">{b.get("total_tokens", 0):,}</div>
            <div class="kpi-value">{_delta_cell(delta.get("total_tokens", 0))}</div>
          </div>
        </div>"""

        # Dimension comparison table
        dim_html = '<div class="section"><h2>Per-Dimension Comparison</h2><table><tr>'
        dim_html += "<th>Dimension</th><th>A Mean</th><th>B Mean</th><th>Δ Mean</th><th>A Pass%</th><th>B Pass%</th><th>Δ Pass%</th></tr>"
        for dim, data in summary.dimensions.items():
            dim_html += f"""<tr>
                <td>{dim}</td>
                <td>{data['agent_a']['mean']:.4f}</td>
                <td>{data['agent_b']['mean']:.4f}</td>
                <td>{_delta_cell(data['mean_delta'])}</td>
                <td>{data['agent_a']['pass_rate']:.1%}</td>
                <td>{data['agent_b']['pass_rate']:.1%}</td>
                <td>{_delta_cell(data['pass_rate_delta'])}</td>
              </tr>"""
        dim_html += "</table></div>"

        # Radar chart for A vs B
        dim_labels = list(summary.dimensions.keys())
        a_means = [summary.dimensions[d]["agent_a"]["mean"] for d in dim_labels]
        b_means = [summary.dimensions[d]["agent_b"]["mean"] for d in dim_labels]
        radar_script = f"""
        (function() {{
          const ctx = document.getElementById('abRadarChart');
          if (!ctx) return;
          new Chart(ctx, {{
            type: 'radar',
            data: {{
              labels: {json.dumps(dim_labels)},
              datasets: [
                {{ label: 'Agent A', data: {json.dumps(a_means)},
                   backgroundColor: 'rgba(59, 130, 246, 0.2)',
                   borderColor: 'rgba(59, 130, 246, 1)', borderWidth: 2 }},
                {{ label: 'Agent B', data: {json.dumps(b_means)},
                   backgroundColor: 'rgba(16, 185, 129, 0.2)',
                   borderColor: 'rgba(16, 185, 129, 1)', borderWidth: 2 }},
              ]
            }},
            options: {{
              responsive: true, maintainAspectRatio: false,
              scales: {{ r: {{ beginAtZero: true, max: 1.0 }} }}
            }}
          }});
        }})();
        """

        sig_html = ""
        if summary.significance:
            sig_html = '<div class="section"><h2>Statistical Significance</h2><table>'
            for metric, data in summary.significance.items():
                if isinstance(data, dict) and "t_statistic" in data:
                    sig_html += f"""<tr>
                        <td>{metric}</td>
                        <td>mean diff: {data.get('mean_diff', 0):.2f}</td>
                        <td>t-stat: {data.get('t_statistic', 0):.4f}</td>
                        <td>{'<span class="badge badge-success">Significant</span>' if data.get('significant') else '<span class="badge badge-fail">Not Significant</span>'}</td>
                      </tr>"""
            sig_html += "</table></div>"

        chart_html = '<div class="section"><h2>Side-by-Side Radar</h2><div class="chart-container"><canvas id="abRadarChart"></canvas></div></div>'

        return kpi_html + chart_html + dim_html + sig_html, radar_script

    # ------------------------------------------------------------------
    # File writer
    # ------------------------------------------------------------------
    def _write_report(
        self,
        base_name: str,
        *,
        title: str,
        subtitle: str,
        body: str | tuple[str, str],
    ) -> Path:
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        # body can be a string or (body_html, chart_script) tuple
        chart_scripts = ""
        if isinstance(body, tuple):
            body_html, chart_scripts = body
        else:
            body_html = body

        html = _PAGE_SHELL.format(
            title=title,
            subtitle=subtitle,
            body=body_html,
            chart_scripts=chart_scripts,
            timestamp=timestamp,
        )
        path = self._output_dir / f"{base_name}.html"
        with open(path, "w", encoding="utf-8") as f:
            f.write(html)
        return path
